from abc import ABC, abstractmethod


class InventoryStorage(ABC):
    @abstractmethod
    def list_labs(self) -> list[dict]: ...

    @abstractmethod
    def add_lab(self, lab: dict) -> dict: ...

    @abstractmethod
    def update_lab(self, lab_id: int, lab: dict) -> bool: ...

    @abstractmethod
    def delete_lab(self, lab_id: int) -> bool: ...

    @abstractmethod
    def list_computers(self, lab_id: int | None = None) -> list[dict]: ...

    @abstractmethod
    def add_computer(self, computer: dict) -> dict: ...

    @abstractmethod
    def update_computer(self, computer_id: int, computer: dict) -> bool: ...

    @abstractmethod
    def delete_computer(self, computer_id: int) -> bool: ...

    @abstractmethod
    def list_lab_items(self, lab_id: int | None = None) -> list[dict]: ...

    @abstractmethod
    def add_lab_item(self, item: dict) -> dict: ...

    @abstractmethod
    def update_lab_item(self, item_id: int, item: dict) -> bool: ...

    @abstractmethod
    def delete_lab_item(self, item_id: int) -> bool: ...

    @abstractmethod
    def close(self) -> None: ...
